#!/usr/bin/env python3
"""run_case.py —— 跑单个用例并采集「逻辑单元 / DFF / CPU 时间 / 整进程峰值内存」。

对齐主办方口径：
  * 缩减率按逐用例计算再取平均；主指标是逻辑单元，DFF 单列。
  * 耗时按 CPU 时间（user+sys），内存按整个进程的峰值。

设计要点：
  * 基线（B0）与候选走**同一后端**（synth_intel -family cycloneiv）、**同一计数阶段**。
  * 每次运行生成独立目录 runs/<run_id>/，内含 result.json、synth.ys、yosys.log、stat.json —— 证据可追溯。
  * PMUX 分析单独起一个 yosys 进程，其耗时单独记为 analyze_time，**不计入 cpu_time**，避免污染计时。

用法：
  python3 scripts/run_case.py --case benchmarks/unit/u02_pmux4_shared_fields.v
  python3 scripts/run_case.py --case x.v --top top --pipeline B1 --repeat 3
  python3 scripts/run_case.py --case x.v --dry-run          # 只看生成的脚本与命令
  python3 scripts/run_case.py --selftest                    # 不依赖 yosys，自检解析与产物逻辑
"""
