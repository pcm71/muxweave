def _write_fake_artifacts(case: Path, stat_json: Path, analyze_json: Path, opt_json: Path) -> None:
    """冒烟模式：不调用 yosys，直接产出结构合法的 stat/analyze/opt 产物。

    用途：① 本机无法安装 Yosys 时验证 runner 的记账与产物逻辑；
          ② 团队等待 Yosys 编译期间先打通实验驱动。
    生成的结果会带 "fake": true，report.py 会把它排除在成绩之外。
    """
    stat_json.write_text(json.dumps({
        "creator": "FAKE stat -json (harness smoke test)",
        "modules": {case.stem: {"num_cells": 120, "num_wires": 100, "num_memories": 0,
                                "cells_by_type": {"$pmux": 2, "$mux": 3, "$and": 40,
                                                  "$not": 25, "$dff": 40, "$_DFF_P_": 10}}},
    }, indent=2, ensure_ascii=False), encoding="utf-8")
    analyze_json.write_text(json.dumps({
        "creator": "FAKE pmux_analyze (harness smoke test)",
        "modules": [{"name": case.stem, "cells": []}],
        "summary": {"pmux_cells": 2, "mux_cells": 3, "cells_with_reuse": 2,
                    "shared_pattern_bits": 8, "max_width": 16, "max_choices": 4},
    }, indent=2, ensure_ascii=False), encoding="utf-8")
    opt_json.write_text(json.dumps({
        "creator": "FAKE pmux_opt (harness smoke test)",
        "fallback": True, "fallback_reason": "fake", "accepted_rules": [],
        "formal_status": "NOT_RUN",
    }, indent=2, ensure_ascii=False), encoding="utf-8")


def do_run(args) -> int:
    case = Path(args.case).resolve()
    if not case.is_file():
        print(f"找不到用例文件：{case}", file=sys.stderr)
        return 2

    cfg = load_pipelines(Path(args.pipelines))
    pipelines = cfg.get("pipelines", {})
    if args.pipeline not in pipelines:
        print(f"未知 pipeline: {args.pipeline}；可选：{', '.join(pipelines)}", file=sys.stderr)
        return 2
    pipe = pipelines[args.pipeline]
    backend = cfg.get("backend", {})

    top = args.top or case.stem
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    run_id = f"{case.stem}__{args.pipeline}__{stamp}"
    run_dir = Path(args.runs_dir).resolve() / run_id
    stat_json = run_dir / "stat.json"
    analyze_json = run_dir / "analyze.json"
    opt_json = run_dir / "opt.json"
    synth_ys = run_dir / "synth.ys"
    analyze_ys = run_dir / "analyze.ys"

    repl = {
        "@@TOP@@": top,
        "@@REPO@@": ROOT,
        "@@STAT_JSON@@": stat_json,
        "@@ANALYZE_JSON@@": analyze_json,
        "@@OPT_JSON@@": opt_json,
    }
    script = build_script(case, top, pipe, backend, repl)
    analyze_script = build_analyze_script(case, top, pipe, repl)

    if args.dry_run:
        print("=== 将写入 %s ===" % synth_ys)
        print(script)
        print("=== 将写入 %s ===" % analyze_ys)
        print(analyze_script)
        print("=== 将执行 ===")
        print(f"{args.yosys} -s {synth_ys}")
        if not args.no_analyze:
            print(f"{args.yosys} -s {analyze_ys}")
        return 0

    run_dir.mkdir(parents=True, exist_ok=True)
    synth_ys.write_text(script, encoding="utf-8")
    analyze_ys.write_text(analyze_script, encoding="utf-8")

    if args.fake_yosys:
        t0 = time.monotonic()
        _write_fake_artifacts(case, stat_json, analyze_json, opt_json)
        runs = [{"returncode": 0, "wall_time": round(time.monotonic() - t0, 4), "cpu_time": None,
                 "peak_process_memory_kb": None, "peak_process_tree_memory_kb": None,
                 "log": "(fake: 未调用 yosys)"}]
        yosys_ver = "FAKE (harness smoke test)"
        print("提示：--fake-yosys 为冒烟模式，产物带 fake=true，不会计入成绩。", file=sys.stderr)
    else:
        if shutil.which(args.yosys) is None and not Path(args.yosys).exists():
            print(f"找不到 yosys 可执行文件：{args.yosys}（先跑 scripts/bootstrap_yosys.sh，"
                  f"或先用 --fake-yosys 验证驱动）", file=sys.stderr)
            return 3

        try:
            yosys_ver = subprocess.run([args.yosys, "-V"], capture_output=True, text=True,
                                       check=False).stdout.strip() or "unknown"
        except OSError:
            yosys_ver = "unknown"

        repeats = max(1, args.repeat)
        runs = []
        for i in range(repeats):
            log = run_dir / ("yosys.log" if repeats == 1 else f"yosys.run{i+1}.log")
            m = run_once([args.yosys, "-s", str(synth_ys)], log)
            m["log"] = log.name
            runs.append(m)
            if m["returncode"] != 0:
                print(f"yosys 退出码 {m['returncode']}，见 {log}", file=sys.stderr)
                break

    ok = all(m["returncode"] == 0 for m in runs)
    wall = statistics.median(m["wall_time"] for m in runs)
    cpus = [m["cpu_time"] for m in runs if m["cpu_time"] is not None]
    peaks = [m["peak_process_tree_memory_kb"] for m in runs if m["peak_process_tree_memory_kb"]]

    metrics = {}
    if ok and stat_json.exists():
        try:
            metrics = parse_stat_json(stat_json, top if args.count_top else None)
        except Exception as exc:  # 保留原始 JSON 供人工核对
            print(f"警告：解析 stat.json 失败：{exc}", file=sys.stderr)

    analyze = {}
    analyze_time = None
    if ok and not args.no_analyze:
        if args.fake_yosys:
            analyze = parse_analyze_json(analyze_json)
        else:
            m = run_once([args.yosys, "-s", str(analyze_ys)], run_dir / "analyze.log")
            analyze_time = m["cpu_time"]
            if m["returncode"] == 0 and analyze_json.exists():
                try:
                    analyze = parse_analyze_json(analyze_json)
                except Exception as exc:
                    print(f"警告：解析 analyze.json 失败：{exc}", file=sys.stderr)
            else:
                print(f"警告：pmux_analyze 退出码 {m['returncode']}（是否已把 pass 编入主程序？）", file=sys.stderr)

    formal_status, formal_time = "NOT_RUN", None
    if ok and args.eqy:
        ft0 = time.monotonic()
        res = subprocess.run(["eqy", args.eqy], cwd=str(ROOT), capture_output=True, text=True, check=False)
        formal_time = round(time.monotonic() - ft0, 4)
        (run_dir / "formal.log").write_text(res.stdout + res.stderr, encoding="utf-8")
        formal_status = "PASS" if res.returncode == 0 else "FAIL"

    result = {
        "run_id": run_id,
        "input": str(case.relative_to(ROOT)) if str(case).startswith(str(ROOT)) else str(case),
        "input_hash": sha256_file(case),
        "top": top,
        "pipeline": args.pipeline,
        "pipeline_desc": pipe.get("desc", ""),
        "baseline_id": args.baseline_id,
        "count_stage": "after synth_intel -family cycloneiv, before write",
        "target_device": "Cyclone IV (synth_intel -family cycloneiv)",
        "tool_versions": {"yosys": yosys_ver},
        "host": {"platform": platform.platform(), "python": platform.python_version(),
                 "cpu_count": os.cpu_count()},
        "repeats": repeats if not args.fake_yosys else 1,
        "returncode": 0 if ok else 1,
        "fake": bool(args.fake_yosys),
        "wall_time": round(wall, 4),
        "cpu_time": round(statistics.median(cpus), 4) if cpus else None,
        "analyze_time": round(analyze_time, 4) if analyze_time else None,
        "peak_process_memory_kb": max(peaks) if peaks else None,
        "peak_process_tree_memory_kb": max(peaks) if peaks else None,
        "measurement_note": ("POSIX getrusage(RUSAGE_CHILDREN)：ru_maxrss 为整个子进程树峰值；"
                             "CPU 时间为 user+sys。Windows 下不可用，请用 WSL2。")
        if measure_supported() else "本机非 POSIX，未采集 CPU/内存（请用 WSL2 或 Linux）",
        "base_cells": metrics.get("num_cells"),
        "base_logic_cells": metrics.get("logic_cells"),
        "dff_base": metrics.get("dff_cells"),
        "cells_by_type": metrics.get("cells_by_type", {}),
        "pmux_count": analyze.get("pmux_cells"),
        "mux_count": analyze.get("mux_cells"),
        "cells_with_reuse": analyze.get("cells_with_reuse"),
        "bits_with_reuse": analyze.get("bits_with_reuse_total"),
        "shared_pattern_bits": analyze.get("shared_pattern_bits"),
        "max_width": analyze.get("max_width"),
        "max_choices": analyze.get("max_choices"),
        "formal_status": formal_status,
        "formal_time": formal_time,
        "fallback": True,
        "fallback_reason": "week1: B0 基线运行，不含自研结构变换",
        "accepted_rules": [],
        "artifacts": [str(p.relative_to(run_dir)) for p in
                      [synth_ys, analyze_ys, stat_json, analyze_json, opt_json,
                       run_dir / "analyze.log"] if p.exists()],
    }
    (run_dir / "result.json").write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")

    print(f"运行目录 : {run_dir}")
    print(f"逻辑单元 : {result['base_logic_cells']}   DFF: {result['dff_base']}")
    print(f"CPU 时间 : {result['cpu_time']} s   墙钟: {result['wall_time']} s")
    print(f"进程峰值 : {result['peak_process_tree_memory_kb']} KB")
    print(f"PMUX     : {result['pmux_count']} 个, 跨位共享位 {result['shared_pattern_bits']}")
    print("提示：单次运行只算 baseline；候选对照请用 --pipeline O_INSERT_A/B 再跑一次，"
          "并用 scripts/report.py 汇总。")
    return 0 if ok else 1


# ----------------------------------------------------------------------------
# 自检：不依赖 yosys，验证解析与产物逻辑
# ----------------------------------------------------------------------------
def do_selftest() -> int:
    fixture_stat = {
        "creator": "Yosys 0.69 (selftest fixture)",
        "modules": {
            "u02_pmux4_shared_fields": {
                # num_cells 必须等于 cells_by_type 之和，保持 fixture 自洽
                "num_cells": 41,
                "num_wires": 90,
                "num_memories": 0,
                "cells_by_type": {"$pmux": 1, "$not": 6, "$and": 20, "$dff": 8,
                                  "$mux": 2, "$_DFF_P_": 4},
            }
        },
    }
    # 分类口径：$mux/$pmux 属于**逻辑单元**（它们要占 LUT），只有 DFF 与 mem 被扣除。
    # 因此 logic = 41 - dff(8+4) - mem(0) = 29
    fixture_analyze = {
        "summary": {"pmux_cells": 1, "mux_cells": 2, "cells_with_reuse": 1,
                    "shared_pattern_bits": 4, "max_width": 8, "max_choices": 4}
    }

    # 自检产物放在工作区内，避免依赖系统临时目录（部分受限环境不可写）
    td = ROOT / ".selftest_tmp"
    if td.exists():
        shutil.rmtree(td, ignore_errors=True)
    td.mkdir(parents=True, exist_ok=True)
    try:
        sp, ap = td / "stat.json", td / "analyze.json"
        sp.write_text(json.dumps(fixture_stat), encoding="utf-8")
        ap.write_text(json.dumps(fixture_analyze), encoding="utf-8")

        m = parse_stat_json(sp)
        checks = []
        checks.append(("num_cells", m["num_cells"], 41))
        checks.append(("logic_cells(含 $mux/$pmux，扣 DFF)", m["logic_cells"], 29))
        checks.append(("dff_cells", m["dff_cells"], 12))
        checks.append(("mem_cells", m["mem_cells"], 0))

        a = parse_analyze_json(ap)
        checks.append(("pmux_cells", a["pmux_cells"], 1))
        checks.append(("shared_pattern_bits", a["shared_pattern_bits"], 4))

        # 脚本生成（repl 提供全部占位符）
        cfg = load_pipelines(DEFAULT_PIPELINES)
        repl = {"@@STAT_JSON@@": sp, "@@ANALYZE_JSON@@": ap, "@@OPT_JSON@@": td / "opt.json"}
        sc = build_script(td / "x.v", "x", cfg["pipelines"]["B0"], cfg["backend"], repl)
        checks.append(("B0 脚本含 synth_intel", "synth_intel -family cycloneiv" in sc, True))
        checks.append(("B0 脚本不含自研 pass", "pmux_opt" not in sc, True))
        sc2 = build_script(td / "x.v", "x", cfg["pipelines"]["O_INSERT_A"], cfg["backend"], repl)
        checks.append(("INSERT_A 含 pmux_opt", "pmux_opt -json" in sc2, True))
        checks.append(("占位符已全部替换(B0)", "@@" not in sc, True))
        checks.append(("占位符已全部替换(INSERT_A)", "@@" not in sc2, True))
        checks.append(("opt.json 路径已写入", str(td / "opt.json") in sc2, True))
        # 缺占位符时必须报错，而不是生成坏脚本
        try:
            build_script(td / "x.v", "x", cfg["pipelines"]["O_INSERT_A"], cfg["backend"], {})
            checks.append(("缺占位符时报错", "no-raise", "raise"))
        except ValueError:
            checks.append(("缺占位符时报错", "raise", "raise"))

        bad = 0
        for name, got, want in checks:
            flag = "OK  " if got == want else "FAIL"
            if got != want:
                bad += 1
            print(f"  [{flag}] {name}: got={got!r} want={want!r}")
        if bad:
            print(f"自检失败：{bad} 项不符")
            return 1
        print("自检通过：stat/analyze 解析、脚本生成、占位符替换、B0 与插入点差异均正确。")
        return 0
    finally:
        shutil.rmtree(td, ignore_errors=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--case", help="Verilog 用例路径")
    ap.add_argument("--top", default=None, help="顶层模块名（默认取文件名去扩展名）")
    ap.add_argument("--pipeline", default="B0", help="configs/pipelines.json 中的 pipeline 名（默认 B0）")
    ap.add_argument("--pipelines", default=str(DEFAULT_PIPELINES), help="pipelines.json 路径")
    ap.add_argument("--runs-dir", default=str(ROOT / "runs"), help="运行目录根（默认 runs/）")
    ap.add_argument("--yosys", default="yosys", help="yosys 可执行文件（默认 PATH 中的 yosys）")
    ap.add_argument("--repeat", type=int, default=1, help="重复次数（取中位数/最大值，默认 1）")
    ap.add_argument("--baseline-id", default="B0", help="写入结果里的基线编号")
    ap.add_argument("--eqy", default=None, help="可选：跑一次 EQY 并记录 formal_status")
    ap.add_argument("--no-analyze", action="store_true", help="跳过 pmux_analyze 单独进程")
    ap.add_argument("--count-top", action="store_true", help="只统计顶层模块的单元数")
    ap.add_argument("--dry-run", action="store_true", help="只打印生成的脚本与命令")
    ap.add_argument("--fake-yosys", action="store_true",
                    help="冒烟模式：不调用 yosys，产出 fake=true 的产物（用于验证驱动，不计入成绩）")
    ap.add_argument("--selftest", action="store_true", help="不依赖 yosys 自检解析与产物逻辑")
    args = ap.parse_args()

    if args.selftest:
        return do_selftest()
    if not args.case:
        ap.print_help()
        return 2
    return do_run(args)


if __name__ == "__main__":
    sys.exit(main())
