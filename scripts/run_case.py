ROOT = HERE.parent
DEFAULT_PIPELINES = ROOT / "configs" / "pipelines.json"


# ----------------------------------------------------------------------------
# 辅助
# ----------------------------------------------------------------------------
def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def load_pipelines(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _substitute(line: str, repl: dict) -> str:
    for key, value in repl.items():
        line = line.replace(key, str(value))
    return line


def build_script(case: Path, top: str, pipe: dict, backend: dict, repl: dict) -> str:
    """生成基线/候选的 yosys 脚本（替换全部占位符；残留占位符直接报错）。"""
    lines = [
        f"# auto-generated by scripts/run_case.py -- pipeline={pipe.get('id', '?')}",
        f"# desc: {pipe.get('desc', '')}",
        f"read_verilog {case}",
        f"hierarchy -top {top}",
    ]
    for p in pipe.get("pre", []):
        lines.append(p)
    for p in pipe.get("opt", []):
        lines.append(p)
    for p in pipe.get("post", []):
        lines.append(p)
    # 允许 pipeline 自带 backend 序列（实验用：例如分段调用 synth_intel 并替换 abc 步骤）
    for p in (pipe.get("backend_passes") or backend.get("passes", [])):
        lines.append(p)
    lines.append("stat")
    lines.append(backend.get("stat", "stat -json @@STAT_JSON@@"))
    lines = [_substitute(l, repl) for l in lines]
    leftover = [l for l in lines if "@@" in l]
    if leftover:
        raise ValueError(
            "生成脚本里仍有未替换的占位符（说明 pipelines.json 用到了 runner 未提供的变量）：\n  "
            + "\n  ".join(leftover)
        )
    return "\n".join(lines) + "\n"


def build_analyze_script(case: Path, top: str, pipe: dict, repl: dict) -> str:
    """PMUX 分析脚本：在 proc（+pre）之后、综合之前分析，此时 $pmux 尚未被映射掉。"""
    lines = [
        "# auto-generated by scripts/run_case.py -- pmux analysis only (read-only)",
        f"read_verilog {case}",
        f"hierarchy -top {top}",
    ]
    for p in pipe.get("pre", []):
        lines.append(p)
    # 保证分析阶段在 proc 之后：某些实验 pipeline 的 pre 为空（backend 自带 proc），
    # 若不补这一步，analyze 会在层次展开后就分析，看不到任何 $pmux。
    if not any(p.strip().startswith("proc") for p in pipe.get("pre", [])):
        lines.append("proc")
    lines.append("pmux_analyze -table -json @@ANALYZE_JSON@@")
    lines = [_substitute(l, repl) for l in lines]
    leftover = [l for l in lines if "@@" in l]
    if leftover:
        raise ValueError("分析脚本里有未替换的占位符：\n  " + "\n  ".join(leftover))
    return "\n".join(lines) + "\n"


# ----------------------------------------------------------------------------
# 资源统计解析（对 stat -json 的输出保持宽容，字段名以实测为准）
# ----------------------------------------------------------------------------
# 注意：classify() 先把类型名转小写，所以这里的候选也必须全小写，否则永不匹配。
DFF_PREFIXES = ("$dff", "$_dff", "$sdff", "$_sdff", "$adff", "$_adff", "$dffe", "$_dffe",
                "$_dff", "cycloneiv_ff", "cycloneiv_ff_", "dffep", "dffeas")


def classify(cell_type: str) -> str:
    t = cell_type.lower()
    if t.startswith(DFF_PREFIXES) or "dff" in t:
        return "dff"
    if t.startswith("$mem") or "memrd" in t or "memwr" in t:
        return "mem"
    return "logic"


def parse_stat_json(path: Path, top: str | None = None) -> dict:
    """解析 Yosys `stat -json`。返回 {num_cells, dff, logic, mem, cells_by_type}。"""
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)

    modules = data.get("modules") or {}
    if not isinstance(modules, dict) or not modules:
        raise ValueError(
            f"{path} 里没有 modules 字段。请确认该文件来自 `stat -json`，"
            f"顶层键有：{sorted(data.keys())[:8]}"
        )

    # Yosys 0.69 的 `stat -json` 结构（已实测）：
    #   {"creator":..., "modules": {"\\top": {...,"num_cells":N,"num_cells_by_type":{...}},
    #                               "design": {同字段，全设计聚合}}}
    # 要点：字段名是 num_cells_by_type（不是 cells_by_type）；"design" 项正合"全设计单元总数"口径。
    def by_type_of(entry: dict) -> dict:
        cand = entry.get("num_cells_by_type") or entry.get("cells_by_type") or {}
        return cand if isinstance(cand, dict) else {}

    if isinstance(modules.get("design"), dict):
        entry = modules["design"]
        total = int(entry.get("num_cells", 0))
        by_type: dict[str, int] = {k: int(v) for k, v in by_type_of(entry).items()}
        entry_used = "design(全设计聚合)"
    else:
        chosen = {top: modules[top]} if (top and top in modules) else modules
        total = 0
        by_type = {}
        for name, mod in chosen.items():
            if not isinstance(mod, dict):
                continue
            total += int(mod.get("num_cells", 0))
            for k, v in by_type_of(mod).items():
                by_type[k] = by_type.get(k, 0) + int(v)
        entry_used = ",".join(sorted(chosen.keys()))

    if by_type:
        logic = sum(v for k, v in by_type.items() if classify(k) == "logic")
        dff = sum(v for k, v in by_type.items() if classify(k) == "dff")
        mem = sum(v for k, v in by_type.items() if classify(k) == "mem")
    else:
        # stat -json 未提供 cells_by_type 时的降级路径：只报总数，DFF 未知
        logic, dff, mem = total, 0, 0

    return {
        "num_cells": total,
        "logic_cells": logic,
        "dff_cells": dff,
        "mem_cells": mem,
        "cells_by_type": dict(sorted(by_type.items(), key=lambda kv: -kv[1])),
        "modules_counted": entry_used,
    }


def parse_analyze_json(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data.get("summary", {})


# ----------------------------------------------------------------------------
# 资源测量
# ----------------------------------------------------------------------------
def measure_supported() -> bool:
    return os.name == "posix"


def rusage():
    import resource  # noqa: PLC0415  (POSIX only)
    return resource.getrusage(resource.RUSAGE_CHILDREN)


def run_once(cmd: list[str], log_path: Path) -> dict:
    """执行一次命令，返回 CPU / 墙钟 / 子进程峰值内存。"""
    t0 = time.monotonic()
    cpu_before = rss_after = None
    if measure_supported():
        ru = rusage()
        cpu_before = ru.ru_utime + ru.ru_stime
    with open(log_path, "w", encoding="utf-8") as log:
        proc = subprocess.run(cmd, stdout=log, stderr=subprocess.STDOUT, check=False)
    wall = time.monotonic() - t0
    cpu = None
    peak_kb = None
    if measure_supported():
        ru = rusage()
        cpu = (ru.ru_utime + ru.ru_stime) - cpu_before
        # RUSAGE_CHILDREN 的 ru_maxrss 是所有已回收子进程的峰值最大值，
        # 本脚本每次调用只跑一个 yosys 子进程（重复次数取最大值），因此该值即"整个进程的峰值"。
        peak_kb = ru.ru_maxrss
        rss_after = ru.ru_maxrss
    return {
        "returncode": proc.returncode,
        "wall_time": round(wall, 4),
        "cpu_time": round(cpu, 4) if cpu is not None else None,
        "peak_process_memory_kb": peak_kb,
        "peak_process_tree_memory_kb": peak_kb,
        "_rss_after": rss_after,
    }


